"""The backing band: turn chord progressions into grooves with MMA (Musical MIDI Accompaniment).

MMA lives in ``engine/mma`` and runs as a separate program. We write a small ``.mma`` file
(tempo, groove, one line per bar of chords), run MMA to get MIDI, and optionally merge the
melody on top with mido.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import mido

ENGINE = Path(__file__).resolve().parents[2] / "engine" / "mma"


class BandError(RuntimeError):
    pass


@dataclass
class Groove:
    name: str
    description: str
    library: str
    family: str          # file the groove is defined in, e.g. "swing"
    family_doc: str


def mma_script() -> Path:
    p = ENGINE / "mma.py"
    if not p.exists():
        raise BandError(f"MMA engine not found at {p}")
    return p


def _run_mma(args: list[str], cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(mma_script()), *args], capture_output=True, text=True,
                          cwd=str(cwd or ENGINE))


def ensure_groove_database() -> None:
    """MMA needs an index of its groove library; build it once (about 2 seconds)."""
    if not any((ENGINE / "lib" / "stdlib").glob(".mmaDB")):
        proc = _run_mma(["-G"])
        if proc.returncode != 0:
            raise BandError(f"MMA could not index its grooves: {proc.stderr or proc.stdout}")


@lru_cache(maxsize=1)
def list_grooves(libraries: tuple[str, ...] = ("stdlib",)) -> list[Groove]:
    """All grooves with their descriptions, parsed from MMA's library files."""
    out = []
    for lib in libraries:
        for f in sorted((ENGINE / "lib" / lib).glob("*.mma")):
            text = f.read_text(errors="replace")
            doc = ""
            m = re.search(r"^Begin Doc\s*(.*?)^End", text, re.S | re.M)
            if m:
                doc = " ".join(m.group(1).split())
            # DefGroove lines may continue with a trailing backslash
            joined = re.sub(r"\\\s*\n\s*", " ", text)
            for gm in re.finditer(r"^DefGroove\s+(\S+)\s*(.*)$", joined, re.M):
                out.append(Groove(gm.group(1), " ".join(gm.group(2).split()), lib, f.stem, doc))
    return out


def mma_source(bars: list[list[str]], groove: str, tempo: int, time_signature: str = "4/4",
               title: str = "Rameau", pickup_beats: int = 0) -> str:
    """Build an MMA file. ``bars`` is a list of bars, each a list of chord symbols per beat.

    ``pickup_beats``: the first bar is a pickup with only this many beats (rests are added before).
    """
    beats_per_bar = int(time_signature.split("/")[0])
    lines = [f"// {title}: generated by Rameau", f"Time {beats_per_bar}", f"TimeSig {time_signature}",
             f"Tempo {tempo}", f"Groove {groove}", ""]
    for i, bar in enumerate(bars, 1):
        cells = list(bar)
        if i == 1 and pickup_beats and len(cells) < beats_per_bar:
            cells = ["z"] * (beats_per_bar - len(cells)) + cells
        cells = (cells + [cells[-1]] * beats_per_bar)[:beats_per_bar] if cells else ["z"] * beats_per_bar
        # MMA uses "/" to mean "same chord as before"
        shown, prev = [], None
        for c in cells:
            shown.append("/" if c == prev and c != "z" else c)
            prev = c
        lines.append(f"{i} " + " ".join(shown))
    return "\n".join(lines) + "\n"


def render_band(source: str, midi_out: Path) -> Path:
    ensure_groove_database()
    with tempfile.TemporaryDirectory() as d:
        src = Path(d) / "song.mma"
        src.write_text(source)
        proc = _run_mma([str(src), "-f", str(Path(midi_out).resolve())], cwd=Path(d))
    if proc.returncode != 0 or not Path(midi_out).exists():
        msg = (proc.stdout + proc.stderr).strip().splitlines()
        raise BandError("MMA failed: " + " ".join(m for m in msg if "Error" in m or "error" in m)[:500])
    return Path(midi_out)


def bars_from_harmonization(h, r=None) -> tuple[list[list[str]], int]:
    """Chord symbols per beat, grouped into bars, plus the number of pickup beats."""
    from .harmonize import chord_symbol

    bars: dict[int, list[str]] = {}
    for t, c in enumerate(h.choices):
        inv = r.inversions[t] if r is not None else 0
        bars.setdefault(c.beat.measure, []).append(chord_symbol(c.label, h.key, inv))
    numbers = sorted(bars)
    first = h.choices[0].beat if h.choices else None
    pickup = len(bars[numbers[0]]) if first is not None and first.beat > 1 else 0
    return [bars[n] for n in numbers], pickup


def parse_chord_text(text: str) -> list[list[str]]:
    """Chord chart text to bars: '| C Am | F G7 | C |' or one bar per line ('C Am', 'F G7').

    Chords in a bar share its beats evenly (2 chords in 4/4 = 2 beats each).
    """
    raw = [b.strip() for b in re.split(r"[|\n]", text) if b.strip()]
    return [b.split() for b in raw]


def expand_to_beats(bars: list[list[str]], beats_per_bar: int = 4) -> list[list[str]]:
    out = []
    for bar in bars:
        if len(bar) >= beats_per_bar:
            out.append(bar[:beats_per_bar])
            continue
        per = beats_per_bar // len(bar)
        cells = []
        for i, c in enumerate(bar):
            n = per if i < len(bar) - 1 else beats_per_bar - per * (len(bar) - 1)
            cells += [c] * n
        out.append(cells)
    return out


def merge_midi(base: Path, overlay: Path, out: Path, overlay_channel: int = 0, overlay_program: int | None = 73) -> Path:
    """Put the tracks of ``overlay`` (e.g. the melody) on top of ``base`` (e.g. the band)."""
    a, b = mido.MidiFile(str(base)), mido.MidiFile(str(overlay))
    merged = mido.MidiFile(type=1, ticks_per_beat=a.ticks_per_beat)
    merged.tracks.extend(a.tracks)
    scale = a.ticks_per_beat / b.ticks_per_beat
    for track in b.tracks:
        nt = mido.MidiTrack()
        carry = 0.0
        for msg in track:
            t = msg.time * scale + carry
            it = int(round(t))
            carry = t - it
            if msg.is_meta and msg.type in ("set_tempo", "time_signature", "key_signature"):
                nt.append(mido.MetaMessage("text", text="", time=it))  # the band file already has these
                continue
            if not msg.is_meta and hasattr(msg, "channel"):
                msg = msg.copy(channel=overlay_channel, time=it)
                if msg.type == "program_change" and overlay_program is not None:
                    msg = msg.copy(program=overlay_program)
            else:
                msg = msg.copy(time=it)
            nt.append(msg)
        if overlay_program is not None:
            nt.insert(0, mido.Message("program_change", channel=overlay_channel, program=overlay_program, time=0))
        merged.tracks.append(nt)
    merged.save(str(out))
    return Path(out)
